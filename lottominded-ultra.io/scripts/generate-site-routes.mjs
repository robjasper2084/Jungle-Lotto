import { access, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(packageRoot, "data", "site-routes.json");
const runtimePath = resolve(packageRoot, "assets", "js", "lm-route-manifest.generated.js");
const sitemapPath = resolve(packageRoot, "sitemap.xml");
const inventoryPath = resolve(packageRoot, "data", "site-route-inventory.generated.json");

function fail(message) {
  throw new Error(`Route manifest: ${message}`);
}

function routePath(route) {
  const href = String(route.href || "").replace(/^\.\//, "").split(/[?#]/)[0];
  return href || "index.html";
}

const manifest = JSON.parse(await readFile(sourcePath, "utf8"));
if (!Array.isArray(manifest.routes) || !manifest.routes.length) fail("routes must be a non-empty array");
if (!/^https:\/\//.test(manifest.productionBaseUrl || "")) fail("productionBaseUrl must use HTTPS");

const ids = new Set();
const canonicals = new Set();
const labels = new Set();
const aliases = new Map();

for (const route of manifest.routes) {
  if (!route.id || ids.has(route.id)) fail(`duplicate or missing id: ${route.id || "(empty)"}`);
  ids.add(route.id);
  if (!route.label || labels.has(route.label.toLowerCase())) fail(`duplicate or missing label: ${route.label || "(empty)"}`);
  labels.add(route.label.toLowerCase());
  if (!route.canonical || canonicals.has(route.canonical)) fail(`duplicate or missing canonical: ${route.canonical || "(empty)"}`);
  canonicals.add(route.canonical);
  if (!route.description || !route.href || !route.file || !route.section) fail(`${route.id} is missing required route fields`);
  if (!route.canonical.startsWith(manifest.productionBaseUrl)) fail(`${route.id} canonical is outside productionBaseUrl`);
  await access(resolve(packageRoot, route.file)).catch(() => fail(`${route.id} points to missing file ${route.file}`));
  for (const alias of route.aliases || []) {
    const normalized = String(alias).split("#")[0];
    if (aliases.has(normalized)) fail(`alias ${normalized} is assigned to multiple routes`);
    aliases.set(normalized, route.id);
  }
}

for (const [alias, routeId] of aliases) {
  const target = manifest.routes.find((route) => route.id === routeId);
  if (alias === String(target.href).split("#")[0]) fail(`alias loop on ${alias}`);
}

const sitemapRoutes = manifest.routes.filter((route) => route.indexable && route.includeInSitemap);
const sitemap = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...sitemapRoutes.map((route) => `  <url><loc>${route.canonical}</loc></url>`),
  "</urlset>",
  "",
].join("\n");

const browserManifest = {
  version: manifest.version,
  productionBaseUrl: manifest.productionBaseUrl,
  routes: manifest.routes,
};
const runtime = [
  "/* Generated by scripts/generate-site-routes.mjs. Do not edit directly. */",
  `(function(root){root.LottoMindRouteManifest=Object.freeze(${JSON.stringify(browserManifest)});})(window);`,
  "",
].join("\n");

const inventory = {
  generatedAt: new Date().toISOString(),
  canonicalRoutes: sitemapRoutes.map((route) => routePath(route)),
  aliases: [...aliases].map(([alias, routeId]) => ({ alias, routeId })),
  routes: manifest.routes.map((route) => ({
    id: route.id,
    file: route.file,
    href: route.href,
    canonical: route.canonical,
    indexable: route.indexable,
  })),
};

await writeFile(runtimePath, runtime, "utf8");
await writeFile(sitemapPath, sitemap, "utf8");
await writeFile(inventoryPath, `${JSON.stringify(inventory, null, 2)}\n`, "utf8");
console.log(`Generated ${manifest.routes.length} routes and ${sitemapRoutes.length} sitemap URLs.`);
