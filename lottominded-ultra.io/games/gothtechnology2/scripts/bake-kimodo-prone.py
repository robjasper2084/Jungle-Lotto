"""Bake the original Kimodo tactical prone take; preserve source provenance."""
from pathlib import Path
import argparse, hashlib, importlib.util, json, shutil
import numpy as np
from scipy.spatial.transform import Rotation, Slerp

PACK=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('athletic',PACK/'scripts/bake-kimodo-athletic.py')
m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)

def main():
 parser=argparse.ArgumentParser(description=__doc__)
 parser.add_argument('--source',type=Path,required=True)
 parser.add_argument('--first',type=int,required=True)
 parser.add_argument('--last',type=int,required=True)
 args=parser.parse_args();source=args.source.resolve();lo,hi=args.first,args.last
 d=np.load(source/'motion.npz',allow_pickle=False);j=d['posed_joints'];roots=d['root_positions']
 if not 0<=lo<hi<len(roots):raise ValueError('Invalid source trim')
 clip=m.extract(source,lo,hi,False);rows=np.asarray(clip['frames']);t=np.linspace(0,1,hi-lo+1);baked_t=np.linspace(0,1,len(rows))
 # Keep absolute height, but no generated world-space horizontal trajectory.
 rows[:,45]=np.interp(baked_t,t,roots[lo:hi+1,1])
 mat=m.basis(j[lo,m.IDX['LeftLeg']]-j[lo,m.IDX['RightLeg']],j[lo,m.IDX['Spine2']]-j[lo,0])
 yaw=Rotation.from_matrix(mat).as_euler('YXZ')[0];inverse=Rotation.from_euler('y',-yaw)
 for side in ('Left','Right'):
  rotations=Rotation.from_matrix(d['global_rot_mats'][lo:hi+1,m.IDX[side+'Foot']])
  delta=inverse*rotations*rotations[0].inv()*inverse.inv()
  rows=np.column_stack([rows,Slerp(t,delta)(baked_t).as_quat()])
 # End-point samples are held, never closed into a loop or time-advanced at idle.
 clip.update(id='kimodo-tactical-prone-v1',generator='NVIDIA Kimodo SOMA-RP-v1.2',frames=np.round(rows,6).tolist(),adaptation='Original controlled kneel, hands, chest descent. Root remains at the game capsule; vertical support fits each rig. Phase reverses for rising; endpoint held until crawl input.',runtimeDownSeconds=1.05,runtimeUpSeconds=1.10)
 (PACK/'ride-core/src/kimodoProneData.ts').write_text('// Generated by scripts/bake-kimodo-prone.py from the original local Kimodo take.\nexport const KIMODO_PRONE = '+json.dumps(clip,separators=(',',':'))+';\n',encoding='utf8')
 art=PACK/'ride-core/art/kimodo-prone';art.mkdir(parents=True,exist_ok=True)
 for name in ('motion.npz','motion.bvh','meta.json','validation.json'):
  if (source/name).exists():shutil.copy2(source/name,art/name)
 (art/'manifest.json').write_text(json.dumps({k:v for k,v in clip.items() if k!='frames'},indent=2),encoding='utf8')
 print(json.dumps({k:v for k,v in clip.items() if k!='frames'},indent=2))

if __name__=='__main__':main()
