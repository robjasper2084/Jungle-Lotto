"""Editable Rigify action masters and compact, sampled gameplay curves.

Run in an isolated Blender 5.2 process. Existing heroes and their walking clips
are read-only inputs. Coordinates in the runtime data are metres / Y-up.
"""
import bpy, json, math
from pathlib import Path
from mathutils import Vector, Matrix, Quaternion

PACK = Path(__file__).resolve().parents[1]
SOURCE = Path("C:/Users/digit/Documents/phone/hero-wheel-animation-20261004")
OUT = PACK / "swoop-source/art/hero-actions-20261017"
OUT.mkdir(parents=True, exist_ok=True)
IDS = ["DS_Man_01", "DS_Hoodie_Woman_01", "DS_Mascot_Suit_01", "DS_Mascot_Hoodie_01", "DS_Armored_Rider_01"]
FPS = 30
# Curve values: hip shift, breathing, chest pitch, chest turn, glance, arm relax.
IDLE = [
 (0, [0,0,0,0,0,0]), (1.2,[.006,.003,.006,.006,.015,.012]),
 (2.8,[.009,-.002,-.003,.009,.022,-.005]),
 (4,[.003,.003,.005,.002,0,.010]),
 (5.4,[-.006,-.002,-.004,-.007,-.020,-.006]),
 (6.8,[-.004,.002,.004,-.005,-.012,.008]), (8,[0,0,0,0,0,0])]
# Holster-to-ready: lift clear of belt, swing in front, join support hand, settle.
# x/y/z offset from ready grip; pitch; support-hand weight; right-hand contact.
DRAW = [
 (0,[-.32,-.16,-.12,1.42,0,0]), (.10,[-.32,-.16,-.12,1.42,0,1]),
 (.22,[-.30,.025,-.10,1.16,0,1]), (.38,[-.15,.03,-.02,.48,.22,1]),
 (.52,[-.025,.015,.025,-.045,.90,1]), (.66,[0,0,0,0,1,1])]
# Pickup: retain user's farm_harvest body take, but grip before lifting,
# hold the handle throughout the lift, set it down before letting go.
PICKUP = [(0,[0,0]),(.1,[0,0]),(.3,[1,0]),(.4,[1,0]),
 (16/30,[1,.12]),(.6,[1,.12]),(.7,[1,0]),(22/30,[1,0]),(25/30,[0,0]),(1,[0,0])]

def controller(name, keys, seconds):
    obj=bpy.data.objects.new(name,None);bpy.context.scene.collection.objects.link(obj)
    obj.empty_display_type='SPHERE';obj.empty_display_size=.04
    for time, values in keys:
        for i,value in enumerate(values):
            obj['v'+str(i)]=float(value)
            obj.keyframe_insert(data_path='["v'+str(i)+'"]',frame=1+time*FPS)
    for layer in obj.animation_data.action.layers:
        for strip in layer.strips:
            for bag in strip.channelbags:
                for curve in bag.fcurves:
                    for point in curve.keyframe_points:
                        point.interpolation='BEZIER'
                        point.handle_left_type=point.handle_right_type='AUTO_CLAMPED'
    samples=[]
    for f in range(round(seconds*FPS)+1):
        bpy.context.scene.frame_set(f+1)
        samples.append([round(obj['v'+str(i)],6) for i in range(len(keys[0][1]))])
    return dict(duration=seconds,samples=samples)

bpy.ops.wm.read_factory_settings(use_empty=True)
bpy.ops.preferences.addon_enable(module='rigify')
data={'idle':controller('Standing_Idle_Curves',IDLE,8),
      'draw':controller('Weapon_Draw_Curves',DRAW,.66),
      'pickup':controller('Wheel_Grip_Lift_Curves',PICKUP,1)}
(OUT/'curves.json').write_text(json.dumps(data,indent=2))
(PACK/'ride-core/src/heroActionData.ts').write_text(
 "// Generated by Blender: scripts/author-hero-actions.py. Do not hand edit.\n"
 +"export const HERO_ACTIONS="+json.dumps(data,separators=(',',':'))+";\n")
bpy.ops.wm.save_as_mainfile(filepath=str(OUT/'Action_Curves.blend'))

# Reuse the proven per-limb solver, without running the old script's entrypoint.
scope={'__file__':str(SOURCE/'Scripts/build_wheel_actions.py')}
exec((SOURCE/'Scripts/build_wheel_actions.py').read_text().split('chosen=')[0],scope)
solve=scope['solve']
def vec(x,y,z): return Vector((x,-z,y))
def sampled(name,t):
    clip=data[name]; rows=clip['samples']; f=max(0,min(1,t/clip['duration']))*(len(rows)-1)
    i=int(f); j=min(i+1,len(rows)-1)
    return [a+(b-a)*(f-i) for a,b in zip(rows[i],rows[j])]

reports=[]
for aid in IDS:
    bpy.ops.wm.open_mainfile(filepath=str(SOURCE/'Blender/Rigify'/f'{aid}_Rigify.blend'))
    scene=bpy.context.scene;scene.render.fps=FPS
    rig=bpy.data.objects[aid+'_Rig']; controls=bpy.data.objects[aid+'_Rigify_Controls']
    controls['Edit_pose']=0.
    for obj in scene.objects:
        if obj.animation_data:obj.animation_data_clear()
    for b in rig.pose.bones:
        b.matrix_basis=Matrix.Identity(4)
    bpy.context.view_layer.update()
    rest={b.name:(rig.matrix_world@b.matrix).copy() for b in rig.pose.bones}
    body_scale=.48 if 'Mascot' in aid else 1.
    actions=[]
    for name,seconds in [('StandingIdle',8),('WeaponDraw',.66),('WeaponHolster',.66),('WheelPickupPolish',2.5)]:
        action=bpy.data.actions.new(name);action.use_fake_user=True
        rig.animation_data_create();rig.animation_data.action=action
        ctrl_action=bpy.data.actions.new(name+'_Rigify');ctrl_action.use_fake_user=True
        controls.animation_data_create();controls.animation_data.action=ctrl_action
        for f in range(round(seconds*FPS)+1):
            t=f/FPS;scene.frame_set(f+1)
            for b in rig.pose.bones:b.matrix_basis=Matrix.Identity(4)
            bpy.context.view_layer.update()
            idle=sampled('idle',t if name=='StandingIdle' else 0)
            hip=rest['Hips'].translation+vec(idle[0],idle[1],0)*body_scale
            pitch=idle[2]; grip=0; lift=0
            if name=='WheelPickupPolish':
                phase=t/seconds;grip,lift=sampled('pickup',phase)
                bend=math.sin(math.pi*phase)**1.6
                hip+=vec(0,-.17*bend,-.08*bend)*body_scale;pitch=.50*bend
            for bone in ['Hips','Spine02','Spine01','Spine']:
                m=rest[bone].copy();m.translation+=hip-rest['Hips'].translation
                m=Matrix.Translation(m.translation)@Quaternion((1,0,0),pitch).to_matrix().to_4x4()@rest[bone].to_quaternion().to_matrix().to_4x4()
                rig.pose.bones[bone].matrix=rig.matrix_world.inverted()@m
                bpy.context.view_layer.update()
            for side in ['Left','Right']:
                solve(rig,side+'UpLeg',side+'Leg',side+'Foot',rest[side+'Foot'].translation,vec(0,0,1),rest[side+'Foot'].to_quaternion())
                shoulder=(rig.matrix_world@rig.pose.bones[side+'Arm'].matrix).translation
                sign=1 if side=='Left' else -1
                target=shoulder+vec(sign*.055,-.47+idle[5],.035)*body_scale
                if name.startswith('Weapon'):
                    motion=sampled('draw',seconds-t if name=='WeaponHolster' else t)
                    ready=rest['Hips'].translation+vec(-.14,.30,.36)*body_scale
                    hand=ready+vec(*motion[:3])*body_scale
                    target=hand if side=='Right' else target.lerp(hand+vec(.12,-.01,.22)*body_scale,motion[4])
                elif name=='WheelPickupPolish':
                    handle=rest['Hips'].translation+vec(0,-.36+lift,.30)*body_scale
                    if side=='Right':target=target.lerp(handle,grip)
                solve(rig,side+'Arm',side+'ForeArm',side+'Hand',target,vec(sign*.7,-.4,-.2),rest[side+'Hand'].to_quaternion())
            for bone in rig.pose.bones:
                bone.keyframe_insert('location',frame=f+1)
                bone.keyframe_insert('rotation_quaternion',frame=f+1)
                if bone.name in controls.pose.bones:
                    cb=controls.pose.bones[bone.name]
                    cb.matrix=controls.matrix_world.inverted()@rig.matrix_world@bone.matrix
                    cb.rotation_mode='QUATERNION'
                    cb.keyframe_insert('location',frame=f+1);cb.keyframe_insert('rotation_quaternion',frame=f+1)
            bpy.context.view_layer.update()
        actions.append(action)
    rig.animation_data.action=actions[0];controls.animation_data.action=bpy.data.actions['StandingIdle_Rigify']
    # The baked deformation actions are portable; matching Rigify controls are
    # retained for editing (set Edit_pose=1). No runtime plugin dependency.
    controls['Edit_pose']=0.;controls['Action polish']='StandingIdle / WeaponDraw / WeaponHolster / WheelPickupPolish'
    scene.frame_start=1;scene.frame_end=241;scene.frame_set(1)
    scene['Runtime data']='heroActionData.ts sampled from Action_Curves.blend'
    bpy.ops.file.pack_all();bpy.ops.wm.save_as_mainfile(filepath=str(OUT/f'{aid}_Actions.blend'))
    reports.append({'hero':aid,'clips':[a.name for a in actions],'rigifyControls':len(controls.pose.bones),'blend':str(OUT/f'{aid}_Actions.blend')})
(OUT/'manifest.json').write_text(json.dumps({'blender':bpy.app.version_string,'plugin':'Rigify','fps':FPS,'heroes':reports},indent=2))
print('HERO_ACTIONS_AUTHORED',len(reports),flush=True)
