#!/usr/bin/env python3
"""Rebuild the three reviewed Conservatory GLBs and preserve the other nine."""
import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import tempfile


def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def sha256(raw):
    return hashlib.sha256(raw).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--assets', required=True, type=Path, help='Existing game public/belle/staged-architecture directory')
    args = parser.parse_args()
    source = Path(__file__).resolve().parent
    assets = args.assets.resolve()
    alignment = json.loads((source / 'source/vestibule_alignment.json').read_text())
    map_bytes = (assets.parent / 'map.json').read_bytes()
    map_blob = hashlib.sha1(b'blob ' + str(len(map_bytes)).encode() + b'\0' + map_bytes).hexdigest()
    require(map_blob == alignment['sourceMapBlobSha'], 'The supplied map blob changed; review its constraints before rebuilding')
    cfg = json.loads(map_bytes)['conservatory']
    require(cfg['center'] == alignment['placement']['center'] and cfg['yaw'] == alignment['placement']['yaw'], 'Original placement changed')
    for wall in alignment['vestibuleWalls']:
        require(cfg['walls'][wall['wallIndex']] == {key: wall[key] for key in ('a', 'b')}, 'Source wall excerpt changed')

    manifest = json.loads((assets / 'manifest.json').read_text())
    require(manifest['productionReady'] is False, 'This command only writes staged study assets')
    site = next(item for item in manifest['models'] if item['placement'].get('gameMapId') == '107310050')
    targets = {item['file']: item for item in site['lods']}
    require(set(targets) == {'Conservatory_Architectural_Study.glb', 'Conservatory_Architectural_Study_LOD1.glb', 'Conservatory_Architectural_Study_LOD2.glb'}, 'Expected exactly three Conservatory outputs')
    others = {item['file']: item for entry in manifest['models'] for item in entry['lods'] if item['file'] not in targets}
    require(len(others) == 9, 'Expected exactly nine untouched assets')
    untouched_before = {}
    for name, contract in others.items():
        raw = (assets / name).read_bytes()
        untouched_before[name] = sha256(raw)
        require(len(raw) == contract['bytes'] and untouched_before[name] == contract['sha256'], 'Existing untouched asset failed its contract: ' + name)

    spec = importlib.util.spec_from_file_location('landmark_source', source / 'build_landmarks.py')
    require(spec is not None and spec.loader is not None, 'Authoring source unavailable')
    author = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(author)
    name, study, _placement = next(item for item in author.STUDIES if item[0] == 'Conservatory_Architectural_Study.glb')
    generated = {}
    with tempfile.TemporaryDirectory(prefix='conservatory-rebuild-') as temporary:
        author.ROOT = Path(temporary)
        (author.ROOT / 'models').mkdir()
        for lod in (0, 1, 2):
            filename = name if lod == 0 else name.replace('.glb', f'_LOD{lod}.glb')
            selection = None if lod == 0 else set(author.LOD_GROUPS[name][lod])
            report = study.export(filename, selection)
            raw = (author.ROOT / 'models' / filename).read_bytes()
            contract = targets[filename]
            require(report['sha256'] == contract['sha256'] and len(raw) == contract['bytes'], 'Generated bytes differ from the reviewed manifest: ' + filename)
            require(report['total_triangles'] == contract['total_triangles'] and report['total_mesh_groups'] == contract['total_mesh_groups'], 'Generated geometry counts changed: ' + filename)
            generated[filename] = raw

    # All three outputs are generated and verified before any target is written.
    for name, raw in generated.items():
        temporary_name = None
        try:
            with tempfile.NamedTemporaryFile(dir=assets, prefix='.conservatory-', delete=False) as stream:
                temporary_name = Path(stream.name)
                stream.write(raw)
            os.replace(temporary_name, assets / name)
        finally:
            if temporary_name is not None:
                temporary_name.unlink(missing_ok=True)
    untouched_after = {name: sha256((assets / name).read_bytes()) for name in others}
    require(untouched_before == untouched_after, 'An asset outside the three Conservatory outputs changed')
    print(json.dumps({'passed': True, 'sourceMapBlobSha': map_blob,
                      'generatorSha256': sha256((source / 'build_landmarks.py').read_bytes()),
                      'rebuilt': [{'file': name, 'bytes': len(raw), 'sha256': sha256(raw)} for name, raw in generated.items()],
                      'otherNineByteIdentical': True, 'otherNineSha256': untouched_after}, indent=2))


if __name__ == '__main__':
    main()
